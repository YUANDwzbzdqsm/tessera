// Builds the two halves the harness loads:
// - lib/index.js: the host plugin, an ES module for Node with Tessera, zod and acorn bundled in, so the profile needs
//   no dependencies installed.
// - lib/client.js: the browser plugin in the harness's lazy-CJS bundle format. Running the file only registers a
//   factory; the module body runs when the harness first materializes the plugin. React comes from the harness's
//   platform module table through the factory's `require`, so the page keeps one React.
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';
import { buildSandbox } from '../../scripts/build-sandbox.mjs';

const here = fileURLToPath(new URL('.', import.meta.url));
const lib = fileURLToPath(new URL('./lib/', import.meta.url));
const pkg = JSON.parse(readFileSync(new URL('./package.json', import.meta.url), 'utf8'));
const PLATFORM = ['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client'];

if (!existsSync(fileURLToPath(new URL('../../packages/runtime/dist/sandbox-worker.js', import.meta.url)))) await buildSandbox();
rmSync(lib, { recursive: true, force: true });

await build({
  root: here,
  configFile: false,
  logLevel: 'warn',
  build: {
    ssr: 'src/host.ts',
    outDir: 'lib',
    emptyOutDir: false,
    minify: false,
    target: 'node22',
    rollupOptions: { output: { format: 'es', entryFileNames: 'index.js' } },
  },
  ssr: { noExternal: true, target: 'node' },
});

await build({
  root: here,
  configFile: false,
  logLevel: 'warn',
  define: { 'process.env.NODE_ENV': '"production"' },
  esbuild: { jsx: 'automatic' },
  build: {
    outDir: 'lib',
    emptyOutDir: false,
    minify: true,
    target: 'es2022',
    lib: { entry: 'src/client.tsx', formats: ['cjs'], fileName: () => 'client.cjs' },
    rollupOptions: { external: PLATFORM, output: { exports: 'named', interop: 'auto' } },
  },
});

const cjs = readFileSync(`${lib}client.cjs`, 'utf8');
rmSync(`${lib}client.cjs`);
writeFileSync(
  `${lib}client.js`,
  `/* ${pkg.name} ${pkg.version}: browser half, generated by build.mjs */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    var module = { exports: {} };
    (function (module, exports, require) {
${cjs}
    })(module, module.exports, require);
    return module.exports;
  },
});
`,
);

for (const file of ['index.js', 'client.js']) {
  console.log(`lib/${file}  ${(readFileSync(`${lib}${file}`).length / 1024).toFixed(0)} KB`);
}
